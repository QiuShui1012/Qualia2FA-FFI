//! `uniffi-bindgen`: generates the Kotlin, Swift and Python bindings for the host
//! platforms.
//!
//! Building the binding generator as a binary of this library keeps the UniFFI version
//! used to generate bindings identical to the one the library was compiled with. A
//! globally installed `uniffi-bindgen` of a different version produces bindings that
//! compile but do not match the library at run time.
//!
//! Usage, from the `FFI/` directory:
//!
//! ```text
//! # Kotlin (shared by the JVM desktop build and Android)
//! cargo run --bin uniffi-bindgen -- generate \
//!     --library target/debug/qualia2fa_ffi.dll \
//!     --language kotlin --out-dir ../UI/bindings
//!
//! # Swift (iOS)
//! cargo run --bin uniffi-bindgen -- generate \
//!     --library target/debug/qualia2fa_ffi.dll \
//!     --language swift --out-dir ../UI/bindings-swift
//! ```
//!
//! The dynamic library is `.dll` on Windows, `.so` on Linux and `.dylib` on macOS; a
//! `staticlib` build (`.a` / `.lib`) works as well.
//!
//! Generated bindings are host-side build products: they are not edited by hand and not
//! committed to this repository, but generated by the host build before compiling.
//! Otherwise the bindings and the interface definition drift apart. See the README.

fn main() {
    uniffi::uniffi_bindgen_main();
}
